#!/usr/bin/env node
/**
 * Generates the dashboard TEST logins (username + password per role) for the local development login
 * (/dev-login). Run: `npm run dev:accounts`  (run again to issue new passwords).
 *
 * Writes:
 *   - src/server/auth/dev-accounts.generated.ts  username → role + scrypt salt/hash (no plain passwords)
 *   - docs/test-users.md                          section "Dashboard test logins" with the plain passwords
 *   - .env.development.local                      DEV_LOGIN_SECRET (signs the test-login cookie), if missing
 * Prints nothing secret. These accounts work ONLY while the development sign-in bypass is active
 * (`next dev` on localhost); production uses Clerk only.
 */
import { randomBytes, randomInt, scryptSync } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");

/** One login per dashboard (role). Display names match the seeded dev users (npm run db:seed). */
const ACCOUNTS = [
  { username: "sw_admin", role: "super_admin", name: "Nebiyu Platform Admin", route: "/admin" },
  { username: "sw_hospital_admin", role: "hospital_admin", name: "Dr. Aster Tadesse (Dil Chora Referral Hospital)", route: "/hospital" },
  { username: "sw_hospital_staff", role: "hospital_staff", name: "Sr. Genet Alemu (Sabian General Hospital)", route: "/hospital" },
  { username: "sw_driver", role: "driver", name: "Abebe Kebede", route: "/driver" },
  { username: "sw_disposal", role: "disposal_operator", name: "Eng. Kassahun Worku (Disposal Site)", route: "/disposal" },
  { username: "sw_efda", role: "efda_officer", name: "Tariku Haile (EFDA)", route: "/regulator" },
];

const ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789";
function password() {
  // 4 groups of 4 unambiguous characters, e.g. "Kp7m-Wq2X-…" (≈ 93 bits)
  const groups = Array.from({ length: 4 }, () =>
    Array.from({ length: 4 }, () => ALPHABET[randomInt(ALPHABET.length)]).join("")
  );
  return groups.join("-");
}

const generated = ACCOUNTS.map((a) => {
  const pw = password();
  const salt = randomBytes(16).toString("hex");
  const hash = scryptSync(pw, salt, 64).toString("hex");
  return { ...a, password: pw, salt, hash };
});

// 1) Server file with hashes only.
const ts = `/* AUTO-GENERATED by scripts/generate-dev-accounts.mjs — do not edit by hand. */
/* Development test logins. Contains scrypt hashes only, never plain passwords. */
import type { Role } from "./access-rules";

export interface DevAccount {
  username: string;
  role: Role;
  salt: string;
  hash: string;
}

export const DEV_ACCOUNTS: readonly DevAccount[] = ${JSON.stringify(
  generated.map(({ username, role, salt, hash }) => ({ username, role, salt, hash })),
  null,
  2
)};
`;
writeFileSync(resolve(ROOT, "src/server/auth/dev-accounts.generated.ts"), ts);

// 2) Docs section with the plain passwords (local project file, test accounts only).
const MD = resolve(ROOT, "docs/test-users.md");
const START = "<!-- dashboard-logins:start -->";
const END = "<!-- dashboard-logins:end -->";
const section = `${START}
## Dashboard test logins (no Clerk) — generated ${new Date().toISOString().slice(0, 16)}Z

Open **http://localhost:3000/dev-login**, enter the username and password, and the dashboard of that role opens.
Works only on the local dev server (\`npm run dev\`); production uses Clerk. Regenerate with \`npm run dev:accounts\`.
Test passwords only — never reuse them anywhere real.

| Dashboard | Username | Password | Signs in as | Opens |
|---|---|---|---|---|
${generated
  .map((g) => `| ${g.role} | \`${g.username}\` | \`${g.password}\` | ${g.name} | \`${g.route}\` |`)
  .join("\n")}
${END}`;
let md = existsSync(MD) ? readFileSync(MD, "utf8") : "# Test users\n";
const re = new RegExp(`${START}[\\s\\S]*?${END}`);
md = re.test(md) ? md.replace(re, section) : `${md.trimEnd()}\n\n${section}\n`;
writeFileSync(MD, md);

// 3) Cookie-signing secret for the test login (dev only).
const ENV_DEV = resolve(ROOT, ".env.development.local");
let envDev = existsSync(ENV_DEV) ? readFileSync(ENV_DEV, "utf8") : "";
if (!/^DEV_LOGIN_SECRET=.{32,}$/m.test(envDev)) {
  envDev = envDev.replace(/^DEV_LOGIN_SECRET=.*\n?/m, "");
  envDev = `${envDev.trimEnd()}\n\n# Signs the /dev-login session cookie (development only).\nDEV_LOGIN_SECRET=${randomBytes(32).toString("hex")}\n`;
  writeFileSync(ENV_DEV, envDev);
}

console.log(`Generated ${generated.length} dashboard test logins.`);
console.log("Usernames and passwords: docs/test-users.md (section 'Dashboard test logins').");
