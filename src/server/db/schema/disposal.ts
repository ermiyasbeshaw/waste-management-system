import { sql } from "drizzle-orm";
import { boolean, check, integer, pgTable, text, uniqueIndex, uuid } from "drizzle-orm/pg-core";
import { filled, id, timestamps, tsz } from "./_common";
import { destructionMethods } from "./catalog";
import { certificateStatus } from "./enums";
import { users } from "./users";
import { wasteRecords } from "./waste";

/**
 * Disposal records (one per waste record). Destruction locks the record FIRST; a locked row cannot be updated
 * or deleted (trigger, CLAUDE.md §9). The operator must have role disposal_operator (trigger).
 */
export const disposalRecords = pgTable(
  "disposal_records",
  {
    id: id(),
    wasteRecordId: uuid("waste_record_id")
      .notNull()
      .references(() => wasteRecords.id, { onDelete: "restrict" }),
    operatorId: uuid("operator_id")
      .notNull()
      .references(() => users.id, { onDelete: "restrict" }),
    receivedAt: tsz("received_at"),
    methodId: uuid("method_id").references(() => destructionMethods.id, { onDelete: "restrict" }),
    destroyedAt: tsz("destroyed_at"),
    locked: boolean("locked").notNull().default(false),
    ...timestamps,
  },
  (t) => [
    uniqueIndex("disposal_records_waste_record_unique").on(t.wasteRecordId),
    // Destruction is recorded with a method and a time, and locks the record (CLAUDE.md §6).
    check(
      "disposal_records_destruction_fields",
      sql`(${t.destroyedAt} IS NOT NULL) = (${t.methodId} IS NOT NULL)`
    ),
    check(
      "disposal_records_locked_needs_destruction",
      sql`NOT ${t.locked} OR ${t.destroyedAt} IS NOT NULL`
    ),
  ]
);

/**
 * Certificates of disposal (CLAUDE.md §5–§6). Generated by a retryable job: PENDING → ISSUED | FAILED.
 * Only ISSUED is publicly valid. Reissue = new row; the old one is REVOKED, so there is at most one
 * non-revoked certificate per disposal record. Number e.g. CD-2026-00017.
 */
export const certificates = pgTable(
  "certificates",
  {
    id: id(),
    certificateNo: text("certificate_no").notNull(),
    disposalRecordId: uuid("disposal_record_id")
      .notNull()
      .references(() => disposalRecords.id, { onDelete: "restrict" }),
    fileKey: text("file_key"),
    sha256: text("sha256"),
    verifyToken: text("verify_token").notNull(),
    status: certificateStatus("status").notNull().default("PENDING"),
    issuedAt: tsz("issued_at"),
    revokedAt: tsz("revoked_at"),
    revokedReason: text("revoked_reason"),
    generationAttempts: integer("generation_attempts").notNull().default(0),
    lastError: text("last_error"),
    ...timestamps,
  },
  (t) => [
    uniqueIndex("certificates_certificate_no_unique").on(t.certificateNo),
    uniqueIndex("certificates_verify_token_unique").on(t.verifyToken),
    uniqueIndex("certificates_one_current_per_disposal")
      .on(t.disposalRecordId)
      .where(sql`${t.status} <> 'REVOKED'`),
    check("certificates_no_format", sql`${t.certificateNo} ~ '^CD-[0-9]{4}-[0-9]{5}$'`),
    check("certificates_verify_token_format", sql`${t.verifyToken} ~ '^[A-Za-z0-9_-]{22,100}$'`),
    check("certificates_sha256_format", sql`${t.sha256} IS NULL OR ${t.sha256} ~ '^[0-9a-f]{64}$'`),
    check(
      "certificates_issued_fields",
      sql`${t.status} NOT IN ('ISSUED', 'REVOKED')
          OR (${t.fileKey} IS NOT NULL AND ${t.sha256} IS NOT NULL AND ${t.issuedAt} IS NOT NULL)`
    ),
    check(
      "certificates_revoked_fields",
      sql`(${t.status} = 'REVOKED') = (${filled(t.revokedReason)} AND ${t.revokedAt} IS NOT NULL)`
    ),
    check("certificates_attempts_min", sql`${t.generationAttempts} >= 0`),
  ]
);
